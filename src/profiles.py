def get_business_summary(ticker: str, sector: str = "", industry: str = "") -> str:
    """
    Get a concise description of what the company does (ทำอะไร คร่าวๆ).
    Falls back to sector and industry if not in curated list.
    """
    clean_ticker = ticker.strip().upper()
    if clean_ticker in CURATED_PROFILES:
        return CURATED_PROFILES[clean_ticker]
    
    # Fallback to translated / formatted industry
    if industry and sector:
        return f"ธุรกิจ {industry} (กลุ่ม {sector})"
    elif industry:
        return f"ธุรกิจ {industry}"
    elif sector:
        return f"กลุ่มอุตสาหกรรม {sector}"
    return "บริษัทจดทะเบียนในตลาดหลักทรัพย์"
